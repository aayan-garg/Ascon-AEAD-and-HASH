#!/usr/bin/env python3
"""
Generate compact C header (kat_vectors.h) for all 2,114 NIST SP 800-232 KATs:
  - 1,025 Ascon-Hash256 vectors (Msg 0..1024 B -> 256-bit MD)
  - 1,089 Ascon-AEAD128 vectors (AD 0..32 B x PT 0..32 B -> CT + 16 B Tag)

All NIST LWC KAT inputs follow deterministic byte progressions:
  - Hash Msg[i]    = i & 0xFF
  - AEAD Key[i]    = i & 0xFF
  - AEAD Nonce[i]  = (0x10 + i) & 0xFF
  - AEAD PT[i]     = (0x20 + i) & 0xFF
  - AEAD AD[i]     = (0x30 + i) & 0xFF

Storing only the verified cryptographic outputs (and exact metadata) compresses
the 646.6 KB dataset to ~66.1 KB so all 2,114 KATs fit inside 128 KB BRAM on
the Digilent Zybo Z7-10 (XC7Z010).
"""

import argparse
import os
import struct

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
KAT_ROOT = os.path.abspath(
    os.path.join(SCRIPT_DIR, "..", "..", "..", "Ascon-AEAD-and-HASH", "reference", "kat")
)


def parse_kat_file(path):
    vecs, cur = [], {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\r\n")
            if not line.strip():
                if cur:
                    vecs.append(cur)
                    cur = {}
            elif "=" in line:
                k, v = line.split("=", 1)
                cur[k.strip()] = v.strip()
    if cur:
        vecs.append(cur)
    return vecs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=os.path.join(SCRIPT_DIR, "..", "fw", "kat_vectors.h"))
    parser.add_argument("--max-hash", type=int, default=1025)
    parser.add_argument("--max-aead", type=int, default=1089)
    args = parser.parse_args()

    hash_vecs = parse_kat_file(os.path.join(KAT_ROOT, "LWC_HASH_KAT_128_256.txt"))
    aead_vecs = parse_kat_file(os.path.join(KAT_ROOT, "LWC_AEAD_KAT_128_128.txt"))

    assert len(hash_vecs) == 1025, f"Expected 1025 Hash vectors, got {len(hash_vecs)}"
    assert len(aead_vecs) == 1089, f"Expected 1089 AEAD vectors, got {len(aead_vecs)}"

    # Verify deterministic inputs and sequential lengths
    for idx, d in enumerate(hash_vecs):
        msg = bytes.fromhex(d["Msg"])
        assert len(msg) == idx, f"Hash idx {idx} len mismatch: {len(msg)}"
        assert msg == bytes(i & 0xFF for i in range(idx)), f"Hash idx {idx} non-deterministic"
        assert len(bytes.fromhex(d["MD"])) == 32

    aead_meta = []
    aead_blob = bytearray()
    for idx, d in enumerate(aead_vecs):
        key = bytes.fromhex(d["Key"])
        nonce = bytes.fromhex(d["Nonce"])
        pt = bytes.fromhex(d["PT"])
        ad = bytes.fromhex(d["AD"])
        ct_tag = bytes.fromhex(d["CT"])
        assert len(key) == 16 and key == bytes(i & 0xFF for i in range(16))
        assert len(nonce) == 16 and nonce == bytes((0x10 + i) & 0xFF for i in range(16))
        assert pt == bytes((0x20 + i) & 0xFF for i in range(len(pt)))
        assert ad == bytes((0x30 + i) & 0xFF for i in range(len(ad)))
        assert len(ct_tag) == len(pt) + 16
        assert len(pt) == idx // 33 and len(ad) == idx % 33, (
            f"AEAD idx {idx}: got pt={len(pt)}, ad={len(ad)}"
        )
        # Pad each record to 4-byte boundary so all Tag reads are naturally word-aligned
        off = len(aead_blob)
        aead_meta.append((len(ad), len(pt), off))
        aead_blob.extend(ct_tag)
        while len(aead_blob) % 4 != 0:
            aead_blob.append(0)

    hash_sel = hash_vecs[: args.max_hash]
    aead_sel_n = min(args.max_aead, len(aead_vecs))
    last_m = aead_meta[aead_sel_n - 1]
    blob_len = last_m[2] + last_m[1] + 16
    while blob_len % 4 != 0:
        blob_len += 1

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by Presentation/kat_board/scripts/gen_kat_header.py */\n")
        f.write("#ifndef KAT_VECTORS_H\n#define KAT_VECTORS_H\n\n#include <stdint.h>\n\n")
        f.write(f"#define NUM_HASH_KATS {len(hash_sel)}U\n")
        f.write(f"#define NUM_AEAD_KATS {aead_sel_n}U\n\n")

        f.write("static const uint32_t HASH_EXP_MD[NUM_HASH_KATS][8] = {\n")
        for idx, d in enumerate(hash_sel):
            md = bytes.fromhex(d["MD"])
            words = struct.unpack("<8I", md)
            wstr = ", ".join(f"0x{w:08X}U" for w in words)
            f.write(f"    {{ {wstr} }}{',' if idx + 1 < len(hash_sel) else ''}\n")
        f.write("};\n\n")

        f.write("typedef struct {\n")
        f.write("    uint16_t ad_len;\n")
        f.write("    uint16_t pt_len;\n")
        f.write("    uint32_t offset;\n")
        f.write("} aead_kat_meta_t;\n\n")

        f.write("static const aead_kat_meta_t AEAD_META[NUM_AEAD_KATS] = {\n")
        for idx in range(aead_sel_n):
            ad_l, pt_l, off = aead_meta[idx]
            f.write(f"    {{ {ad_l:2d}U, {pt_l:2d}U, {off:5d}U }}{',' if idx + 1 < aead_sel_n else ''}\n")
        f.write("};\n\n")

        f.write(f"static const uint8_t AEAD_EXP_BLOB[{blob_len}] __attribute__((aligned(4))) = {{\n")
        for i in range(0, blob_len, 16):
            chunk = aead_blob[i : min(i + 16, blob_len)]
            hstr = ", ".join(f"0x{b:02X}" for b in chunk)
            comma = "," if (i + 16 < blob_len) else ""
            f.write(f"    {hstr}{comma}\n")
        f.write("};\n\n")
        f.write("#endif /* KAT_VECTORS_H */\n")

    total_table_bytes = len(hash_sel) * 32 + aead_sel_n * 8 + blob_len
    print(
        f"[GEN_KAT] Wrote {args.out}: Hash={len(hash_sel)} ({len(hash_sel)*32} B), "
        f"AEAD={aead_sel_n} (meta={aead_sel_n*8} B + blob={blob_len} B), "
        f"Total table={total_table_bytes} B ({total_table_bytes/1024:.2f} KB)"
    )


if __name__ == "__main__":
    main()

