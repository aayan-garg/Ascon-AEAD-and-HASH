#!/usr/bin/env python3
"""
gen_perm_vectors.py — Generate random + directed permutation test vectors
for tb_permutation_1r/2r/half enhanced random testing.
Uses reference/pyascon/ascon.py as oracle.

Outputs:
  tb/vectors/perm_random_vectors.svh  — SystemVerilog include with localparams

Usage: python scripts/gen_perm_vectors.py
"""
import sys, os, random, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "reference" / "pyascon"))
ROOT = pathlib.Path(__file__).resolve().parent.parent

# Import ascon permutation
from ascon import ascon_permutation

ROUND_SETS = [6, 8, 12]  # rounds used by AEAD/Hash modes
N_RANDOM = 20            # random vectors per round count

def state_to_64list(state):
    """state is list of 5 ints (64-bit). Return as list."""
    return list(state)

def run_perm(state_in, rounds):
    """Run ascon_permutation and return output state as list of 5 ints."""
    s = list(state_in)
    ascon_permutation(s, rounds)
    return s

def fmt64(v):
    return f"64'h{v & 0xFFFFFFFFFFFFFFFF:016X}"

random.seed(0xDEADBEEF)

vectors = []  # list of (rounds, in[5], out[5])

# Directed: all-zeros, all-ones, identity-like
directed_states = [
    [0]*5,
    [0xFFFFFFFFFFFFFFFF]*5,
    [0x0123456789ABCDEF, 0xFEDCBA9876543210, 0xDEADBEEFCAFEBABE, 0x0102030405060708, 0xA5A5A5A5A5A5A5A5],
    # SP 800-232 Appendix A init state for AEAD128
    [0x00001000808c0001, 0x0000000000000000, 0x0000000000000000, 0x0000000000000000, 0x0000000000000000],
]

for r in ROUND_SETS:
    for s in directed_states:
        out = run_perm(s, r)
        vectors.append((r, s, out))
    for _ in range(N_RANDOM):
        s = [random.getrandbits(64) for _ in range(5)]
        out = run_perm(s, r)
        vectors.append((r, s, out))

N = len(vectors)
out_path = ROOT / "tb" / "vectors" / "perm_random_vectors.svh"
out_path.parent.mkdir(parents=True, exist_ok=True)

with open(out_path, "w") as f:
    f.write("// AUTO-GENERATED by scripts/gen_perm_vectors.py — DO NOT EDIT\n")
    f.write(f"// {N} permutation vectors (directed + random), rounds in {ROUND_SETS}\n\n")
    f.write(f"localparam int PERM_N_VECS = {N};\n")
    f.write(f"localparam logic [3:0] PERM_ROUNDS [{N}] = '{{\n")
    f.write(",\n".join(f"  4'd{r}" for r,_,_ in vectors))
    f.write("\n};\n\n")
    for xi in range(5):
        f.write(f"localparam logic [63:0] PERM_IN_X{xi} [{N}] = '{{\n")
        f.write(",\n".join(f"  {fmt64(s[xi])}" for _,s,_ in vectors))
        f.write("\n};\n\n")
    for xi in range(5):
        f.write(f"localparam logic [63:0] PERM_OUT_X{xi} [{N}] = '{{\n")
        f.write(",\n".join(f"  {fmt64(o[xi])}" for _,_,o in vectors))
        f.write("\n};\n\n")

print(f"[gen_perm_vectors] Written {N} vectors to {out_path}")
